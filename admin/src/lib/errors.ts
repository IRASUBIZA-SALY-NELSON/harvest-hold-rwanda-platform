export function errorMessage(e: unknown): string {
  const code = (e as { code?: string })?.code;
  const d = (e as { details?: { min?: number; max?: number } })?.details;
  if (code === 'targetOutOfRange' && d?.min !== undefined) return `The target must be between ${d.min}°C and ${d.max}°C for this crop.`;
  if (code === 'invalidDuration' && d?.max) return `Choose a duration between 1 and ${d.max} minutes.`;
  return (code && MESSAGES[code]) || MESSAGES.unknown;
}
