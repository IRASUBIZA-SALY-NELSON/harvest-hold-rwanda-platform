import fs from 'node:fs/promises';
import path from 'node:path';

import { Injectable, Logger, type OnApplicationBootstrap, type OnModuleDestroy } from '@nestjs/common';
import sharp from 'sharp';

import { ApiError } from '../../common/api-error.js';
import { Database, type Queryable } from '../../common/database.service.js';
import { newId } from '../../common/ids.js';
import { config, rules } from '../../config.js';

export type PhotoKind = 'listing' | 'checkin' | 'profile';
export type PhotoSize = 'full' | 'thumb';

const FULL_PX = 1600;
const THUMB_PX = 480;
const ACCEPTED = new Set(['jpeg', 'png', 'webp', 'avif', 'heif']);

/** Where photo files live. Local disk now; an S3-compatible store can implement the same three calls. */
interface PhotoStore {
  write(id: string, size: PhotoSize, data: Buffer): Promise<void>;
  read(id: string, size: PhotoSize): Promise<Buffer | null>;
  remove(id: string): Promise<void>;
}

class DiskStore implements PhotoStore {
  private file(id: string, size: PhotoSize) {
    // ids are generated by us (prefix + hex), never taken from a request path unchecked
    return path.join(config.uploadsDir, 'photos', id.slice(-2), `${id}${size === 'thumb' ? '.thumb' : ''}.webp`);
  }
  async write(id: string, size: PhotoSize, data: Buffer) {
    const f = this.file(id, size);
    await fs.mkdir(path.dirname(f), { recursive: true });
    await fs.writeFile(f, data);
  }
  async read(id: string, size: PhotoSize) {
    return fs.readFile(this.file(id, size)).catch(() => null);
  }
  async remove(id: string) {
    await Promise.all((['full', 'thumb'] as const).map((s) => fs.rm(this.file(id, s), { force: true })));
  }
}

export interface PhotoRow {
  id: string;
  owner_id: string;
  kind: PhotoKind;
  entity_id: string | null;
  status: 'active' | 'removed';
  [key: string]: any;
}

/**
 * Photos: crops on listings, crates at check-in, profile pictures.
 * Every upload is decoded and re-encoded: the file type is checked by content (not by name),
 * the picture is turned upright, resized, and saved as WebP without any metadata, so the GPS
 * position a phone camera writes into a photo never leaves the farmer's phone.
 */
@Injectable()
export class MediaService implements OnApplicationBootstrap, OnModuleDestroy {
  private store: PhotoStore = new DiskStore();
  private log = new Logger('Media');
  private timer?: NodeJS.Timeout;

  constructor(private db: Database) {}

  onApplicationBootstrap() {
    if (config.test) return;
    const run = () => this.purge().catch((e) => this.log.error(e));
    void run();
    this.timer = setInterval(run, 6 * 3_600_000);
  }

  onModuleDestroy() {
    if (this.timer) clearInterval(this.timer);
  }

  isValidId(id: string) {
    return /^ph-[0-9a-f]{12}$/.test(id);
  }

  async process(input: Buffer): Promise<{ full: Buffer; thumb: Buffer; width: number; height: number }> {
    let meta: Awaited<ReturnType<ReturnType<typeof sharp>['metadata']>>;
    try {
      meta = await sharp(input, { limitInputPixels: 50_000_000 }).metadata();
    } catch {
      throw new ApiError('unsupportedImage', 415);
    }
    if (!meta.format || !ACCEPTED.has(meta.format)) throw new ApiError('unsupportedImage', 415);
    const base = () => sharp(input, { limitInputPixels: 50_000_000 }).rotate(); // upright from EXIF, then EXIF is dropped
    try {
      const full = await base().resize(FULL_PX, FULL_PX, { fit: 'inside', withoutEnlargement: true }).webp({ quality: 80 }).toBuffer({ resolveWithObject: true });
      const thumb = await base().resize(THUMB_PX, THUMB_PX, { fit: 'cover', position: 'attention' }).webp({ quality: 72 }).toBuffer();
      return { full: full.data, thumb, width: full.info.width, height: full.info.height };
    } catch {
      throw new ApiError('unsupportedImage', 415);
    }
  }

  async save(ownerId: string, kind: PhotoKind, entityId: string, input: Buffer, db: Queryable = this.db.pool) {
    if (input.length > rules.photos.maxBytes) throw new ApiError('imageTooLarge', 413);
    const { full, thumb, width, height } = await this.process(input);
    const id = newId('ph');
    await this.store.write(id, 'full', full);
    await this.store.write(id, 'thumb', thumb);
    const position = (await this.db.one<{ n: number }>("SELECT count(*) AS n FROM photos WHERE kind = $1 AND entity_id = $2 AND status = 'active'", [kind, entityId], db))?.n ?? 0;
    return this.db.one<PhotoRow>(
      'INSERT INTO photos (id, owner_id, kind, entity_id, position, width, height, bytes) VALUES ($1, $2, $3, $4, $5, $6, $7, $8) RETURNING *',
      [id, ownerId, kind, entityId, position, width, height, full.length],
      db
    );
  }

  async read(id: string, size: PhotoSize) {
    return this.store.read(id, size);
  }

  /** Hides a photo everywhere. The file is kept for 30 days in case the decision is reversed (see purge). */
  async remove(id: string, by: string, reason: string | null) {
    return this.db.one<PhotoRow>(
      "UPDATE photos SET status = 'removed', removed_by = $2, removed_reason = $3, removed_at = now() WHERE id = $1 AND status = 'active' RETURNING *",
      [id, by, reason]
    );
  }

  async restore(id: string) {
    // A photo whose file was already purged cannot come back.
    return this.db.one<PhotoRow>(
      "UPDATE photos SET status = 'active', removed_by = NULL, removed_reason = NULL, removed_at = NULL WHERE id = $1 AND status = 'removed' AND purged_at IS NULL RETURNING *",
      [id]
    );
  }

  /** Active photo ids of an entity, in order. */
  async idsFor(kind: PhotoKind, entityId: string): Promise<string[]> {
    const rows = await this.db.query<{ id: string }>("SELECT id FROM photos WHERE kind = $1 AND entity_id = $2 AND status = 'active' ORDER BY position, created_at", [kind, entityId]);
    return rows.map((r) => r.id);
  }

  /** Active photo ids for many entities at once. */
  async idsForMany(kind: PhotoKind, entityIds: string[]): Promise<Map<string, string[]>> {
    const map = new Map<string, string[]>();
    if (!entityIds.length) return map;
    const rows = await this.db.query<{ id: string; entity_id: string }>(
      "SELECT id, entity_id FROM photos WHERE kind = $1 AND entity_id = ANY($2) AND status = 'active' ORDER BY position, created_at",
      [kind, entityIds]
    );
    for (const r of rows) map.set(r.entity_id, [...(map.get(r.entity_id) ?? []), r.id]);
    return map;
  }

  /** Deletes files of photos removed more than 30 days ago. */
  async purge() {
    const rows = await this.db.query<{ id: string }>(
      "SELECT id FROM photos WHERE status = 'removed' AND purged_at IS NULL AND removed_at < now() - interval '30 days'"
    );
    for (const r of rows) {
      await this.store.remove(r.id);
      await this.db.query('UPDATE photos SET purged_at = now() WHERE id = $1', [r.id]);
    }
    if (rows.length) this.log.log(`Deleted the files of ${rows.length} removed photo(s)`);
    return rows.length;
  }
}
